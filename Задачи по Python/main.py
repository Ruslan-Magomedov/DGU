def zodiac_sign(zodiac: str) -> str:
    match zodiac.title():
        case 'Овен' | 'Лев' | 'Стрелец':
            print('Огненный')
        case 'Телец' | 'Дева' | 'Козерог':
            print('Земной')
        case 'Близнецы' | 'Весы' | 'Водолей':
            print('Воздушный')
        case 'Рак' | 'Скорпион' | 'Рыбы':
            print('Водный')
        case _:
            print('Нет данных')



