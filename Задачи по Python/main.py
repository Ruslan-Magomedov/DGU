'''
Задача 3.
В отделе работают 3 сотрудника, которые получают заработную плату в рублях. Требуется определить: 
на сколько зарплата самого высокооплачиваемого из них отличается от самого низкооплачиваемого.
Входные данные
Размеры зарплат всех сотрудников вводятся в одну строку через пробел. 
Каждая заработная плата – это натуральное число, не превышающее 105. И гарантируется ,что все зарплаты различны
Выходные данные
Необходимо вывести одно целое число — разницу между максимальной и минимальной зарплатой.
Примечание: функциями min и max, а также сортировками пользоваться нельзя, мы же условный оператор изучаем)
'''

def max_min_money(money: str) -> int:
    a, b, c = map(int, money.split())
    mx, mn = 0, 0

    # ищем макмимальное число
    if a > b and a > c:
        mx = a
    elif b > c and b > a:
        mx = b
    else:
        mx = c

    # ищем минимальное число
    if a < b and a < c:
        mn = a
    elif b < c and b < a:
        mn = b
    else:
        mn = c

    return mx-mn



